%% Export labels and visualize K1/K2/K3 sample distributions
% This script post-processes completed results from:
%   evaluate_KMD_implementations_TDS_benchmark_0622.m
% It does not repeat any KMD calculation.

baseDir = fileparts(mfilename('fullpath'));
resultDir = fullfile(baseDir, 'KMD_implementation_evaluation_0622');
outputDir = fullfile(resultDir, 'label_distributions_0622');
if ~exist(outputDir, 'dir')
    mkdir(outputDir);
end

methodCodes = {'K1', 'K2', 'K3'};
methodNames = {'Exact DMD', 'Companion DMD', 'Hankel DMD'};
observationWindows = [50, 15];

% Color definitions shared by all figures.
safeColor = [0.08, 0.42, 0.72];
unsafeColor = [0.82, 0.24, 0.12];
correctSafeColor = [0.73, 0.84, 0.92];
correctUnsafeColor = [0.80, 0.80, 0.80];
falseSecureColor = [0.70, 0.00, 0.08];
falseUnsafeColor = [0.95, 0.55, 0.05];
invalidColor = [0.35, 0.35, 0.35];

allLabelTables = cell(numel(methodCodes), numel(observationWindows));
allResults = cell(numel(methodCodes), numel(observationWindows));

%% Load each completed result and export sample-level labels
for methodIndex = 1:numel(methodCodes)
    for windowIndex = 1:numel(observationWindows)
        methodCode = methodCodes{methodIndex};
        methodName = methodNames{methodIndex};
        observationWindow = observationWindows(windowIndex);

        resultFile = fullfile(resultDir, sprintf( ...
            'results_%s_%ds.mat', methodCode, observationWindow));
        if ~exist(resultFile, 'file')
            error('Completed result file not found: %s', resultFile);
        end

        loaded = load(resultFile);
        required = {'result', 'benchmarkLabels', 'benchmarkValid', 'parameters'};
        requireVariables(loaded, required, resultFile);

        result = loaded.result;
        parameters = loaded.parameters;
        benchmarkLabels = loaded.benchmarkLabels(:);
        benchmarkValid = loaded.benchmarkValid(:);
        predictedLabels = result.PredictedLabels(:);
        criticalDamping = result.CriticalDamping(:);
        elapsedTime = result.ElapsedTime(:);
        kmdValid = result.KMDValid(:);

        nSamples = size(parameters, 1);
        sampleIndex = (1:nSamples)';
        evaluationMask = benchmarkValid & kmdValid & ...
            isfinite(predictedLabels);

        correctUnsafe = evaluationMask & ...
            benchmarkLabels == 0 & predictedLabels == 0;
        correctSafe = evaluationMask & ...
            benchmarkLabels == 1 & predictedLabels == 1;
        falseSecure = evaluationMask & ...
            benchmarkLabels == 0 & predictedLabels == 1;
        falseUnsafe = evaluationMask & ...
            benchmarkLabels == 1 & predictedLabels == 0;
        invalid = ~evaluationMask;

        classification = strings(nSamples, 1);
        classification(correctUnsafe) = "Correct unsafe";
        classification(correctSafe) = "Correct safe";
        classification(falseSecure) = "False-secure";
        classification(falseUnsafe) = "False-unsafe";
        classification(invalid) = "Invalid/not evaluated";

        kmdState = strings(nSamples, 1);
        kmdState(kmdValid & predictedLabels == 1) = "Safe";
        kmdState(kmdValid & predictedLabels == 0) = "Unsafe";
        kmdState(~kmdValid | ~isfinite(predictedLabels)) = "Invalid";

        sampleTable = table( ...
            sampleIndex, ...
            parameters(:, 1), ...
            parameters(:, 2), ...
            benchmarkLabels, ...
            benchmarkValid, ...
            predictedLabels, ...
            kmdState, ...
            criticalDamping, ...
            kmdValid, ...
            elapsedTime, ...
            classification, ...
            'VariableNames', { ...
                'SampleIndex', ...
                'PG6_pu', ...
                'PG8_pu', ...
                'TDSBenchmarkLabel', ...
                'TDSBenchmarkValid', ...
                'KMDLabel', ...
                'KMDState', ...
                'CriticalDampingRatio', ...
                'KMDValid', ...
                'KMDComputationTime_s', ...
                'BenchmarkComparison' ...
            });

        csvFile = fullfile(outputDir, sprintf( ...
            '%s_%ds_sample_labels.csv', methodCode, observationWindow));
        xlsxFile = fullfile(outputDir, sprintf( ...
            '%s_%ds_sample_labels.xlsx', methodCode, observationWindow));
        matFile = fullfile(outputDir, sprintf( ...
            '%s_%ds_sample_labels.mat', methodCode, observationWindow));

        writetable(sampleTable, csvFile);
        writetable(sampleTable, xlsxFile);
        save(matFile, 'sampleTable', 'methodCode', 'methodName', ...
            'observationWindow', 'parameters', 'benchmarkLabels', ...
            'benchmarkValid', 'predictedLabels', 'criticalDamping', ...
            'kmdValid', 'elapsedTime', 'classification');

        allLabelTables{methodIndex, windowIndex} = sampleTable;
        allResults{methodIndex, windowIndex} = struct( ...
            'MethodCode', methodCode, ...
            'MethodName', methodName, ...
            'ObservationWindow', observationWindow, ...
            'Parameters', parameters, ...
            'BenchmarkLabels', benchmarkLabels, ...
            'BenchmarkValid', benchmarkValid, ...
            'PredictedLabels', predictedLabels, ...
            'CriticalDamping', criticalDamping, ...
            'KMDValid', kmdValid, ...
            'CorrectUnsafe', correctUnsafe, ...
            'CorrectSafe', correctSafe, ...
            'FalseSecure', falseSecure, ...
            'FalseUnsafe', falseUnsafe, ...
            'Invalid', invalid, ...
            'Metrics', result.Metrics);

        fprintf(['Exported %s, %d s: %d valid labels, ' ...
            '%d false-secure, %d false-unsafe.\n'], ...
            methodCode, observationWindow, sum(evaluationMask), ...
            sum(falseSecure), sum(falseUnsafe));

        %% Individual raw KMD-label distribution
        labelFig = figure( ...
            'Color', 'w', ...
            'Units', 'pixels', ...
            'Position', [100, 80, 820, 680], ...
            'PaperPositionMode', 'auto', ...
            'Renderer', 'painters');
        ax = axes(labelFig);
        hold(ax, 'on');

        unsafeMask = kmdValid & predictedLabels == 0;
        safeMask = kmdValid & predictedLabels == 1;

        hUnsafe = scatter(ax, ...
            parameters(unsafeMask, 1), parameters(unsafeMask, 2), ...
            22, unsafeColor, 'x', 'LineWidth', 0.9);
        hSafe = scatter(ax, ...
            parameters(safeMask, 1), parameters(safeMask, 2), ...
            15, safeColor, 'o', 'filled', 'MarkerEdgeColor', 'none');
        hInvalid = scatter(ax, ...
            parameters(invalid, 1), parameters(invalid, 2), ...
            36, invalidColor, 's', 'LineWidth', 0.8);

        formatAxes(ax, methodName, observationWindow);
        legend([hSafe, hUnsafe, hInvalid], ...
            {'KMD safe', 'KMD unsafe', 'Invalid/not evaluated'}, ...
            'Location', 'southoutside', ...
            'Orientation', 'horizontal', ...
            'FontName', 'Times New Roman', ...
            'FontSize', 12, ...
            'Box', 'off');
        hold(ax, 'off');

        exportFigure(labelFig, outputDir, sprintf( ...
            '%s_%ds_KMD_label_distribution', ...
            methodCode, observationWindow), [7.5, 6.2]);
        close(labelFig);

        %% Individual benchmark-comparison distribution
        errorFig = figure( ...
            'Color', 'w', ...
            'Units', 'pixels', ...
            'Position', [100, 80, 820, 680], ...
            'PaperPositionMode', 'auto', ...
            'Renderer', 'painters');
        errorAx = axes(errorFig);
        hold(errorAx, 'on');

        hCorrectSafe = scatter(errorAx, ...
            parameters(correctSafe, 1), parameters(correctSafe, 2), ...
            11, correctSafeColor, 'o', ...
            'filled', 'MarkerEdgeColor', 'none');
        hCorrectUnsafe = scatter(errorAx, ...
            parameters(correctUnsafe, 1), parameters(correctUnsafe, 2), ...
            12, correctUnsafeColor, 'o', ...
            'filled', 'MarkerEdgeColor', 'none');
        hFalseUnsafe = scatter(errorAx, ...
            parameters(falseUnsafe, 1), parameters(falseUnsafe, 2), ...
            44, falseUnsafeColor, '^', ...
            'filled', ...
            'MarkerEdgeColor', [0.45, 0.20, 0.00], ...
            'LineWidth', 0.7);
        hFalseSecure = scatter(errorAx, ...
            parameters(falseSecure, 1), parameters(falseSecure, 2), ...
            66, falseSecureColor, 'd', ...
            'filled', ...
            'MarkerEdgeColor', [0.25, 0.00, 0.02], ...
            'LineWidth', 1.0);
        hInvalid2 = scatter(errorAx, ...
            parameters(invalid, 1), parameters(invalid, 2), ...
            36, invalidColor, 's', 'LineWidth', 0.8);

        formatAxes(errorAx, methodName, observationWindow);
        metrics = result.Metrics;
        annotationText = sprintf([ ...
            'Accuracy: %.2f%%\\newline' ...
            'Unsafe recall: %.2f%%\\newline' ...
            'False-secure: %d\\newline' ...
            'False-unsafe: %d'], ...
            100 * metrics.Accuracy, ...
            100 * metrics.UnsafeRecall, ...
            metrics.FP, metrics.FN);
        text(errorAx, 0.98, 0.97, annotationText, ...
            'Units', 'normalized', ...
            'HorizontalAlignment', 'right', ...
            'VerticalAlignment', 'top', ...
            'FontName', 'Times New Roman', ...
            'FontSize', 11.5, ...
            'BackgroundColor', 'white', ...
            'EdgeColor', [0.40, 0.40, 0.40], ...
            'Margin', 5);

        legend([hCorrectSafe, hCorrectUnsafe, hFalseSecure, ...
                hFalseUnsafe, hInvalid2], ...
            {'Correct safe', 'Correct unsafe', 'False-secure', ...
             'False-unsafe', 'Invalid'}, ...
            'Location', 'southoutside', ...
            'Orientation', 'horizontal', ...
            'FontName', 'Times New Roman', ...
            'FontSize', 11, ...
            'Box', 'off');
        hold(errorAx, 'off');

        exportFigure(errorFig, outputDir, sprintf( ...
            '%s_%ds_benchmark_comparison_distribution', ...
            methodCode, observationWindow), [7.5, 6.2]);
        close(errorFig);
    end
end

