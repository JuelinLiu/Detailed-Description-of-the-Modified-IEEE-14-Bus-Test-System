function requireVariables(data, names, fileName)
for index = 1:numel(names)
    if ~isfield(data, names{index})
        error('File %s does not contain variable "%s".', ...
            fileName, names{index});
    end
end
end


function formatAxes(ax, methodName, observationWindow)
title(ax, sprintf('%s, %d-s observation window', ...
    methodName, observationWindow), ...
    'FontName', 'Times New Roman', ...
    'FontSize', 16, ...
    'FontWeight', 'bold');
xlabel(ax, '$P_{G6}$ (p.u.)', ...
    'Interpreter', 'latex', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 18);
ylabel(ax, '$P_{G8}$ (p.u.)', ...
    'Interpreter', 'latex', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 18);
xlim(ax, [-0.02, 1.42]);
ylim(ax, [-0.02, 1.02]);
axis(ax, 'square');
grid(ax, 'on');
box(ax, 'on');
ax.FontName = 'Times New Roman';
ax.FontSize = 14;
ax.LineWidth = 1.1;
ax.TickDir = 'out';
ax.Layer = 'top';
ax.GridAlpha = 0.10;
end


function axesArray = createSixPanelAxes(fig)
xPositions = [0.075, 0.565];
yPositions = [0.700, 0.400, 0.100];
width = 0.385;
height = 0.235;
axesArray = gobjects(3, 2);
for row = 1:3
    for col = 1:2
        axesArray(row, col) = axes(fig, ...
            'Position', [xPositions(col), yPositions(row), width, height]); %#ok<LAXES>
    end
end
end


function formatCombinedAxes(ax, methodName, observationWindow, row, col)
panelLetters = {'(a)', '(b)'; '(c)', '(d)'; '(e)', '(f)'};
title(ax, sprintf('%s %s, %d s', ...
    panelLetters{row, col}, methodName, observationWindow), ...
    'FontName', 'Times New Roman', ...
    'FontSize', 13, ...
    'FontWeight', 'bold');
if row == 3
    xlabel(ax, '$P_{G6}$ (p.u.)', ...
        'Interpreter', 'latex', ...
        'FontName', 'Times New Roman', ...
        'FontSize', 15);
end
if col == 1
    ylabel(ax, '$P_{G8}$ (p.u.)', ...
        'Interpreter', 'latex', ...
        'FontName', 'Times New Roman', ...
        'FontSize', 15);
end
xlim(ax, [-0.02, 1.42]);
ylim(ax, [-0.02, 1.02]);
axis(ax, 'square');
grid(ax, 'on');
box(ax, 'on');
ax.FontName = 'Times New Roman';
ax.FontSize = 11.5;
ax.LineWidth = 1.0;
ax.TickDir = 'out';
ax.Layer = 'top';
ax.GridAlpha = 0.10;
end


function exportFigure(fig, outputDir, baseName, paperSize)
fullBaseName = fullfile(outputDir, baseName);
savefig(fig, [fullBaseName, '.fig']);
set(fig, 'PaperUnits', 'inches');
set(fig, 'PaperSize', paperSize);
set(fig, 'PaperPosition', [0, 0, paperSize]);
print(fig, [fullBaseName, '.png'], '-dpng', '-r600');
print(fig, [fullBaseName, '.pdf'], '-dpdf', '-painters');
print(fig, [fullBaseName, '.eps'], '-depsc', '-painters');
end

function exportFinalFigure(fig, outputDir, baseName)
fullBaseName = fullfile(outputDir, baseName);
savefig(fig, [fullBaseName, '.fig']);
exportgraphics(fig, [fullBaseName, '.jpg'], 'Resolution', 600);
exportgraphics(fig, [fullBaseName, '.pdf'], 'ContentType', 'vector');
print(fig, [fullBaseName, '.eps'], '-depsc', '-r600');
end
